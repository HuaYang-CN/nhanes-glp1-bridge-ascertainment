args<-commandArgs(trailingOnly=TRUE)
stopifnot(length(args)==3L)
module<-args[1];CONFIG_FILE<-args[2];RELEASE_ROOT<-normalizePath(args[3],winslash="/",mustWork=TRUE)
if(!grepl("^[a-z0-9_/]+[.]R$",module)||grepl("[.][.]",module))stop("Invalid module path")
source(file.path(RELEASE_ROOT,"src/runtime.R"),encoding="UTF-8")
print_environment()
cat("MODULE:",module,"\n")
conditions<-list();status<-0L
tryCatch(withCallingHandlers(source(file.path(RELEASE_ROOT,"src",module),encoding="UTF-8",chdir=FALSE),warning=function(w){conditions[[length(conditions)+1L]]<<-data.frame(type="warning",message=conditionMessage(w),call=paste(deparse(conditionCall(w)),collapse=" "))}),error=function(e){status<<-1L;conditions[[length(conditions)+1L]]<<-data.frame(type="error",message=conditionMessage(e),call=paste(deparse(conditionCall(e)),collapse=" "));cat("ERROR:",conditionMessage(e),"\n")})
tag<-gsub("[/]","_",sub("[.]R$","",module))
if(length(conditions)) write_csv(bind_rows(conditions),file.path(OUTPUT_DIR,"logs",paste0(tag,"_conditions.csv")))
writeLines(c(capture.output(sessionInfo()),capture.output(.libPaths()),capture.output(expected_versions)),file.path(OUTPUT_DIR,"logs",paste0(tag,"_environment.txt")))
cat("EXIT:",status,"\n")
quit(save="no",status=status)
